"""
Linear Regression for house price prediction using Housing.csv.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

RANDOM_STATE = 42
DATA_PATH = "/content/sample_data/Housing.csv"
OUT = "."  # plots are saved to the current folder

# 1. Load data
df = pd.read_csv(DATA_PATH)

# Id is only a row number, so it is not used as a feature
X = df.drop(columns=["Id", "Price"])
y = df["Price"]

numeric_features = ["Area", "Bedrooms", "Bathrooms", "Floors", "YearBuilt"]
categorical_features = ["Location", "Condition", "Garage"]

# 2. Train/test split
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=RANDOM_STATE
)

# 3. Preprocessing: scale numeric columns, one-hot encode categorical columns
preprocessor = ColumnTransformer(transformers=[
    ("num", Pipeline([
        ("impute", SimpleImputer(strategy="median")),
        ("scale", StandardScaler()),
    ]), numeric_features),
    ("cat", Pipeline([
        ("impute", SimpleImputer(strategy="most_frequent")),
        ("onehot", OneHotEncoder(handle_unknown="ignore", drop="first")),
    ]), categorical_features),
])

# 4. Model
model = Pipeline([
    ("prep", preprocessor),
    ("reg", LinearRegression()),
])

# 5. Cross-validation on training data
cv_r2 = cross_val_score(model, X_train, y_train, cv=5, scoring="r2")
print("5-fold CV R² scores:", np.round(cv_r2, 4))
print("Mean CV R²:", round(cv_r2.mean(), 4))

# 6. Fit and evaluate on the test set
model.fit(X_train, y_train)
y_pred = model.predict(X_test)

mae = mean_absolute_error(y_test, y_pred)
rmse = np.sqrt(mean_squared_error(y_test, y_pred))
r2 = r2_score(y_test, y_pred)

print(f"\nTest MAE:  ${mae:,.0f}")
print(f"Test RMSE: ${rmse:,.0f}")
print(f"Test R²:   {r2:.4f}")

# 7. Coefficients (scaled numeric features; categorical effects relative to the dropped category)
feature_names = model.named_steps["prep"].get_feature_names_out()
coefs = pd.Series(model.named_steps["reg"].coef_, index=feature_names)
print("\nCoefficients (sorted by size):")
print(coefs.sort_values(key=abs, ascending=False).round(2).to_string())
print(f"\nIntercept: {model.named_steps['reg'].intercept_:,.2f}")

# 8. Plot predicted vs actual
fig, ax = plt.subplots(figsize=(7, 6))
ax.scatter(y_test, y_pred, alpha=0.4)
lims = [min(y.min(), y_pred.min()), max(y.max(), y_pred.max())]
ax.plot(lims, lims, "r--", label="Perfect prediction")
ax.set_xlabel("Actual Price")
